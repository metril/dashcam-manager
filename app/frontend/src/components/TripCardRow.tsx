import { AlertTriangle, Camera, CameraOff, Car, Fuel, Film, Gauge, HardDrive, Route, Zap } from 'lucide-react'
import { useNavigate } from 'react-router-dom'
import { useState } from 'react'
import type { TripCard } from '../types'
import { formatBytes, formatClockTime, formatDuration } from '../lib/format'
import { formatDistance, formatFuel, formatSpeed, useUnits } from '../lib/units'
import ClassBadges from './ClassBadges'
import Tooltip from './Tooltip'

interface Props {
  trip: TripCard
}

export default function TripCardRow({ trip }: Props) {
  const navigate = useNavigate()
  const units = useUnits()
  // The cover thumbnail is generated by a background job (or on first
  // request) and can 404 briefly right after a scan, or permanently if
  // ffmpeg couldn't read the segment — fall back to the placeholder icon
  // rather than showing a broken-image glyph.
  const [thumbFailed, setThumbFailed] = useState(false)
  const showThumb = trip.cover_thumb != null && !thumbFailed

  return (
    <button
      type="button"
      onClick={() => navigate(`/footage/trips/${trip.id}`)}
      className="flex w-full items-center gap-4 rounded-lg border border-border bg-surface/40 px-4 py-3 text-left transition-colors hover:border-text-muted hover:bg-surface"
    >
      <div className="flex size-14 shrink-0 items-center justify-center rounded-md bg-surface-2/80 text-text-muted">
        {showThumb ? (
          <img
            src={trip.cover_thumb!}
            alt=""
            className="size-14 rounded-md object-cover"
            onError={() => setThumbFailed(true)}
          />
        ) : (
          <Film className="size-5" strokeWidth={1.5} />
        )}
      </div>

      <div className="flex min-w-0 flex-1 flex-col gap-1.5">
        <div className="flex items-baseline gap-2">
          <span className="text-[13px] font-semibold text-text tabular-nums">
            {formatClockTime(trip.started_at)}
          </span>
          <span className="text-xs text-text-muted">{formatDuration(trip.duration_s)}</span>
          <span className="ml-auto flex items-center gap-1.5 text-text-muted">
            <Tooltip content={trip.front ? 'Front camera' : 'No front camera'}>
              <span>
                {trip.front ? (
                  <Camera className="size-3.5 text-text-muted" strokeWidth={2} />
                ) : (
                  <CameraOff className="size-3.5" strokeWidth={2} />
                )}
              </span>
            </Tooltip>
            <Tooltip content={trip.rear ? 'Rear camera' : 'No rear camera'}>
              <span>
                {trip.rear ? (
                  <Camera className="size-3.5 text-text-muted" strokeWidth={2} />
                ) : (
                  <CameraOff className="size-3.5" strokeWidth={2} />
                )}
              </span>
            </Tooltip>
          </span>
        </div>

        <ClassBadges summary={trip.summary} />

        <div className="flex flex-wrap items-center gap-3 text-xs text-text-muted">
          <span className="flex items-center gap-1">
            <Route className="size-3" />
            {trip.segment_count} segments
          </span>
          <span className="flex items-center gap-1">
            <HardDrive className="size-3" />
            {formatBytes(trip.bytes)}
          </span>
          {trip.max_speed_mps != null && (
            <span className="flex items-center gap-1">
              <Gauge className="size-3" />
              {formatSpeed(trip.max_speed_mps, units, 'mps')} max
            </span>
          )}
          {trip.unreadable_count > 0 && (
            <span>
              {trip.unreadable_count} unreadable
            </span>
          )}
          {trip.obd?.distance_m != null && (
            <span className="flex items-center gap-1">
              <Car className="size-3" />
              {formatDistance(trip.obd.distance_m, units)}
            </span>
          )}
          {trip.obd?.fuel_l != null && (
            <span className="flex items-center gap-1">
              <Fuel className="size-3" />
              {formatFuel(trip.obd.fuel_l, units)}
            </span>
          )}
          {trip.obd != null && trip.obd.event_count > 0 && (
            <span className="flex items-center gap-1">
              <Zap className="size-3" />
              {trip.obd.event_count} event{trip.obd.event_count === 1 ? '' : 's'}
            </span>
          )}
        </div>
        {trip.obd != null && (trip.obd.mil || trip.obd.dtc_count > 0) && (
          <span className="flex w-fit items-center gap-1 rounded-sm bg-danger/15 px-1.5 py-0.5 text-xs font-medium text-danger">
            <AlertTriangle className="size-3" strokeWidth={2} />
            {trip.obd.mil ? 'MIL' : ''}
            {trip.obd.mil && trip.obd.dtc_count > 0 ? ' · ' : ''}
            {trip.obd.dtc_count > 0 ? `${trip.obd.dtc_count} DTC${trip.obd.dtc_count === 1 ? '' : 's'}` : ''}
          </span>
        )}
      </div>
    </button>
  )
}
